  function propertyQuestion(index, random = Math.random) {
    const [q, answer, wrong, explain] = PROPERTY_QUESTIONS[index],
      options = [answer, ...wrong];
    for (let i = options.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      [options[i], options[j]] = [options[j], options[i]];
    }
    return { topic: "properties", q, answer, options, explain, unit: "" };
  }
